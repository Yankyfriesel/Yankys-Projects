// Turns the manual's text (English and Hebrew) into plain text for the question helper, and
// writes it to src/server/assistant/knowledge.ts. Run after the manual text changes:
//   node manual/make-knowledge.mjs
// [[some.key]] becomes the words the screen itself uses, so the helper names buttons exactly.
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");

const lookup = (messages, key) => key.split(".").reduce((n, p) => n?.[p], messages);

function plainText(lang, content, messages) {
  const rich = (text) =>
    String(text)
      .replace(/\[\[([\w.]+)\]\]/g, (_, key) => {
        const value = lookup(messages, key);
        if (typeof value !== "string") throw new Error(`no ${key} in ${lang}`);
        return `“${value}”`;
      })
      .replace(/\*\*(.+?)\*\*/g, "$1")
      .replace(/`(.+?)`/g, "$1");

  const leaves = (node) =>
    Object.values(node).flatMap((v) => (typeof v === "string" ? [v] : leaves(v)));

  const out = [];
  content.chapters.forEach((chapter, i) => {
    out.push(`\n# ${i + 1}. ${rich(chapter.title)}`);
    if (chapter.intro) out.push(rich(chapter.intro));
    for (const block of chapter.blocks) {
      switch (block.type) {
        case "h3":
        case "h4":
          out.push(`\n## ${rich(block.text)}`);
          break;
        case "p":
          out.push(rich(block.text));
          break;
        case "ul":
          out.push(...block.items.map((item) => `- ${rich(item)}`));
          break;
        case "ol":
          out.push(...block.items.map((item, n) => `${n + 1}. ${rich(item)}`));
          break;
        case "note":
        case "tip":
        case "warn":
          out.push(`${block.label}: ${rich(block.text)}`);
          break;
        case "table":
          out.push(block.head.map(rich).join(" | "));
          out.push(...block.rows.map((row) => row.map(rich).join(" | ")));
          break;
        case "fig":
          out.push(`[Picture: ${rich(block.caption)}]`);
          if (block.legend) out.push(...block.legend.map((l, n) => `  (${n + 1}) ${rich(l)}`));
          break;
        case "flow":
          out.push(...block.steps.map((s, n) => `${n + 1}) ${rich(s[0])}: ${rich(s[1])}`));
          break;
        case "perms": {
          const perm = messages.admin.perm;
          for (const [screen, node] of Object.entries(perm)) {
            out.push(`- ${screen}: ${leaves(node).join("; ")}`);
          }
          break;
        }
        default:
          break; // row of pictures: nothing to say in words
      }
    }
  });
  return out.join("\n").replace(/\n{3,}/g, "\n\n").trim();
}

const result = {};
for (const lang of ["en", "he"]) {
  const content = (await import(pathToFileURL(path.join(root, "manual", "content", `${lang}.mjs`)).href)).default;
  const messages = JSON.parse(readFileSync(path.join(root, "messages", `${lang}.json`), "utf8"));
  result[lang] = plainText(lang, content, messages);
}

const file = path.join(root, "src", "server", "assistant", "knowledge.ts");
writeFileSync(
  file,
  `/* eslint-disable */\n// Generated by manual/make-knowledge.mjs from the manual's text. Do not edit by hand.\n` +
    `export const KNOWLEDGE: Record<"en" | "he", string> = ${JSON.stringify(result, null, 2)};\n`,
);
console.log(`knowledge: en ${result.en.length} characters, he ${result.he.length} characters -> ${file}`);
